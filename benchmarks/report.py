"""``python benchmarks/report.py`` — render the sweep results (BUILD_PLAN §7).

Reads ``benchmarks/results/{model}.json`` for every matrix row and produces the
README-ready artifacts: ``benchmarks/results/REPORT.md`` (headline table, accuracy
by category, per-row provenance) and ``benchmarks/results/comparison.svg`` (the
accuracy-vs-cost frontier). The report degrades gracefully: rows without results —
the local follow-up, an interrupted sweep — render as pending lines, and the chart
appears once at least one complete row exists (§7: "the plan and report must
degrade gracefully to API-only").

The chart follows the dataviz method: one series (models are labeled points, not
color-coded series), marks in the validated slot-1 blue for each mode, ink/grid
from the chrome tokens, dark mode selected via ``prefers-color-scheme`` inside the
SVG so the committed file adapts to the reader's GitHub theme. Partial rows are
excluded from the chart (their accuracy is not final) and say so in the subtitle;
every plotted value is also in the adjacent tables, so nothing is chart-gated.
"""

from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path
from typing import Any

if __package__ is None or __package__ == "":  # `python benchmarks/report.py`
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from benchmarks.sweep import (
    DEFAULT_MATRIX_PATH,
    DEFAULT_RESULTS_DIR,
    SweepMatrix,
    load_matrix,
    load_results_doc,
    results_file,
)
from evals.types import CATEGORIES

REPORT_NAME = "REPORT.md"
CHART_NAME = "comparison.svg"


def load_row_results(
    matrix: SweepMatrix, results_dir: Path
) -> tuple[list[dict[str, Any]], list[str]]:
    """(results docs in report order, pending matrix model ids).

    Order: matrix rows, then followups, then any extra results files in the
    directory (an off-matrix --model run still shows up rather than vanishing).
    """
    docs: list[dict[str, Any]] = []
    pending: list[str] = []
    for model in matrix.model_ids:
        path = results_file(results_dir, model)
        if path.exists():
            docs.append(load_results_doc(path))
        else:
            pending.append(model)
    known = set(matrix.model_ids)
    for path in sorted(results_dir.glob("*.json")):
        try:
            doc = load_results_doc(path)
        except ValueError:
            continue
        if doc["model"] not in known and path.name == f"{doc['model']}.json":
            docs.append(doc)
    return docs, pending


# ── formatting ───────────────────────────────────────────────────────────────────


def _fmt_seconds(ms: int) -> str:
    return f"{ms / 1000:.1f}s"


def _fmt_rate(rate: float) -> str:
    return f"{100 * rate:.1f}%"


def _fmt_usd(value: str | None, decimals: int = 2) -> str:
    if value is None:
        return "—"
    return f"${float(value):,.{decimals}f}"


def _scored(doc: dict[str, Any]) -> str:
    cell = f"{doc['n_scored']}/{doc['n_questions']}"
    return cell if doc.get("complete") else f"{cell} †"


def _label(doc: dict[str, Any]) -> str:
    return str(doc["model"]) + ("" if doc.get("complete") else " †")


# ── REPORT.md ────────────────────────────────────────────────────────────────────


def render_report_md(matrix: SweepMatrix, docs: list[dict[str, Any]], pending: list[str]) -> str:
    lines = [
        "# Model benchmark sweep",
        "",
        "_Generated by `benchmarks/report.py` from `benchmarks/results/*.json` — do not_",
        "_edit by hand; re-run the script after a sweep._",
        "",
        f"- suite `{matrix.suite}` · track `{matrix.track}` · judge `{matrix.judge_model}` "
        "(pinned across rows, D-031)",
        "- **$/query** is the agent loop's metered cost per scored question — what serving "
        "the query costs at list prices. Judge spend is harness overhead, carried "
        "separately in the provenance section.",
        "- **overall** is the suite-weighted mean of per-question scores, each the "
        "*minimum* of its tier scores (a right number via a forbidden process fails).",
        "",
    ]
    if not docs:
        lines += [
            "No results yet — run `python benchmarks/run_sweep.py` (API rows) and see "
            "`benchmarks/LOCAL.md` for the local row.",
            "",
        ]
    else:
        lines += [
            "| model | overall | $/query | p50 | p95 | mean iters | tool errors "
            "| runs exhausted | scored | run spend |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for doc in docs:
            runs = doc["runs"]
            tools = doc["tool_calls"]
            lines.append(
                f"| {_label(doc)} | {doc['overall_score']:.1f} "
                f"| {_fmt_usd(doc['usd_per_query'], 4)} "
                f"| {_fmt_seconds(doc['latency_ms_p50'])} "
                f"| {_fmt_seconds(doc['latency_ms_p95'])} "
                f"| {doc['iterations_mean']:.1f} "
                f"| {_fmt_rate(tools['error_rate'])} "
                f"| {runs['exhausted']}/{runs['n']} "
                f"| {_scored(doc)} "
                f"| {_fmt_usd(doc['total_cost_usd'])} |"
            )
        if any(not doc.get("complete") for doc in docs):
            lines += [
                "",
                "† partial run — the budget cap stopped it early; scores cover the "
                "questions scored so far. Resume with `python benchmarks/run_sweep.py "
                "--model <id> --resume <eval_run_id>`.",
            ]
        lines.append("")
    if pending:
        for model in pending:
            note = (
                " — follow-up row, run per `benchmarks/LOCAL.md`"
                if any(row.model == model for row in matrix.followups)
                else ""
            )
            lines.append(f"- *pending:* `{model}`{note}")
        lines.append("")

    if docs:
        lines += ["## Accuracy by category", ""]
        lines.append("| category | " + " | ".join(_label(doc) for doc in docs) + " |")
        lines.append("|---|" + "---:|" * len(docs))
        for category in CATEGORIES:
            row: list[str] = [category]
            present = False
            for doc in docs:
                bucket = doc["categories"].get(category)
                row.append("—" if bucket is None else f"{bucket['score']:.1f}")
                present = present or bucket is not None
            if present:
                lines.append("| " + " | ".join(row) + " |")
        lines += [
            "",
            f"![Accuracy vs cost per query]({CHART_NAME})",
            "",
            "## Row provenance",
            "",
        ]
        for doc in docs:
            price = doc["price"]
            price_note = f" ({price['note']})" if price["note"] else ""
            tokens = doc["tokens"]
            lines.append(
                f"- `{doc['model']}` — eval run `{str(doc['eval_run_id'])[:8]}` · git "
                f"`{doc.get('git_sha') or '?'}` · {doc['recorded_at']} · "
                f"${price['usd_per_mtok_in']}/${price['usd_per_mtok_out']} per Mtok"
                f"{price_note} · budget ${doc['budget_usd']} · spend "
                f"{_fmt_usd(doc['total_cost_usd'])} = agent {_fmt_usd(doc['agent_cost_usd'])} "
                f"+ judge {_fmt_usd(doc['judge_cost_usd'])} · "
                f"{tokens['input']:,} in / {tokens['output']:,} out tokens · "
                f"T2 violations {doc['t2_violations']}"
            )
        lines.append("")
    return "\n".join(lines)


# ── comparison.svg (accuracy vs $/query frontier) ────────────────────────────────

_SVG_W, _SVG_H = 720, 440
_PLOT = {"left": 64.0, "top": 84.0, "right": _SVG_W - 36.0, "bottom": _SVG_H - 64.0}

_SVG_STYLE = """\
    .surface { fill: #fcfcfb; }
    .ink-primary { fill: #0b0b0b; }
    .ink-secondary { fill: #52514e; }
    .ink-muted { fill: #898781; }
    .grid { stroke: #e1e0d9; }
    .axis { stroke: #c3c2b7; }
    .dot { fill: #2a78d6; stroke: #fcfcfb; }
    @media (prefers-color-scheme: dark) {
      .surface { fill: #1a1a19; }
      .ink-primary { fill: #ffffff; }
      .ink-secondary { fill: #c3c2b7; }
      .ink-muted { fill: #898781; }
      .grid { stroke: #2c2c2a; }
      .axis { stroke: #383835; }
      .dot { fill: #3987e5; stroke: #1a1a19; }
    }"""


def _nice_ceiling(value: float) -> float:
    """Smallest 1/2/2.5/5 x 10^k at or above ``value`` (clean axis maximum)."""
    if value <= 0:
        return 1.0
    exponent = math.floor(math.log10(value))
    for mantissa in (1.0, 2.0, 2.5, 5.0, 10.0):
        candidate = mantissa * 10.0**exponent
        if candidate >= value - 1e-12:
            return candidate
    raise AssertionError("unreachable: mantissa 10.0 always covers")


def _tick_format(step: float) -> int:
    """Decimal places that render the tick step exactly (2..4)."""
    return min(4, max(2, -math.floor(math.log10(step)))) if step < 1 else 2


def render_comparison_svg(docs: list[dict[str, Any]]) -> str | None:
    """The frontier chart over complete rows; None when nothing is plottable."""
    rows = [d for d in docs if d.get("complete") and d.get("usd_per_query") is not None]
    if not rows:
        return None
    excluded = [str(d["model"]) for d in docs if d not in rows]

    points = [
        (str(d["model"]), float(str(d["usd_per_query"])), float(d["overall_score"])) for d in rows
    ]
    x_max = _nice_ceiling(max(x for _, x, _ in points) * 1.15)
    x_step = x_max / 5
    decimals = _tick_format(x_step)
    left, top, right, bottom = _PLOT["left"], _PLOT["top"], _PLOT["right"], _PLOT["bottom"]

    def sx(value: float) -> float:
        return left + (value / x_max) * (right - left)

    def sy(value: float) -> float:
        return bottom - (value / 100.0) * (bottom - top)

    subtitle = "core suite · platform track · overall min-of-tiers score vs agent-loop $/query"
    if excluded:
        subtitle += " · partial rows excluded: " + ", ".join(excluded)

    parts: list[str] = [
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {_SVG_W} {_SVG_H}" '
        f'font-family="system-ui, -apple-system, \'Segoe UI\', sans-serif" role="img" '
        f'aria-label="Scatter chart of model accuracy against cost per query">',
        "  <title>Accuracy vs cost per query</title>",
        f"  <style>\n{_SVG_STYLE}\n  </style>",
        f'  <rect class="surface" x="0" y="0" width="{_SVG_W}" height="{_SVG_H}"/>',
        '  <text class="ink-primary" x="24" y="34" font-size="15" '
        'font-weight="600">Accuracy vs cost per query</text>',
        f'  <text class="ink-muted" x="24" y="54" font-size="11">{subtitle}</text>',
    ]
    for tick in range(0, 101, 25):
        y = sy(tick)
        css = "axis" if tick == 0 else "grid"
        parts.append(
            f'  <line class="{css}" x1="{left}" y1="{y:.1f}" x2="{right}" y2="{y:.1f}" '
            'stroke-width="1"/>'
        )
        parts.append(
            f'  <text class="ink-muted" x="{left - 8}" y="{y + 4:.1f}" font-size="11" '
            f'text-anchor="end" style="font-variant-numeric: tabular-nums">{tick}</text>'
        )
    for index in range(6):
        value = index * x_step
        x = sx(value)
        if index:
            parts.append(
                f'  <line class="grid" x1="{x:.1f}" y1="{top}" x2="{x:.1f}" y2="{bottom}" '
                'stroke-width="1"/>'
            )
        parts.append(
            f'  <text class="ink-muted" x="{x:.1f}" y="{bottom + 18}" font-size="11" '
            f'text-anchor="middle" style="font-variant-numeric: tabular-nums">'
            f"${value:.{decimals}f}</text>"
        )
    parts.append(
        f'  <line class="axis" x1="{left}" y1="{top}" x2="{left}" y2="{bottom}" stroke-width="1"/>'
    )
    parts.append(
        f'  <text class="ink-muted" x="{(left + right) / 2:.1f}" y="{bottom + 38}" '
        'font-size="11" text-anchor="middle">cost per query (USD, agent loop)</text>'
    )
    parts.append(
        f'  <text class="ink-muted" x="20" y="{(top + bottom) / 2:.1f}" font-size="11" '
        f'text-anchor="middle" transform="rotate(-90 20 {(top + bottom) / 2:.1f})">'
        "overall score</text>"
    )

    # Labels: right of the dot by default, flipped near the right edge; a later
    # label that would sit on an earlier one (same side, close x) drops 14px.
    placed: list[tuple[str, float, float]] = []
    for name, x_value, y_value in sorted(points, key=lambda p: (sy(p[2]), p[0])):
        x, y = sx(x_value), sy(y_value)
        side = "start" if x <= right - 150 else "end"
        label_x = x + 10 if side == "start" else x - 10
        label_y = y + 4
        for prev_side, prev_x, prev_y in placed:
            if prev_side == side and abs(label_x - prev_x) < 150 and abs(label_y - prev_y) < 14:
                label_y = prev_y + 14
        label_y = min(label_y, bottom - 4)
        placed.append((side, label_x, label_y))
        parts.append(f'  <circle class="dot" cx="{x:.1f}" cy="{y:.1f}" r="5.5" stroke-width="2"/>')
        parts.append(
            f'  <text class="ink-secondary" x="{label_x:.1f}" y="{label_y:.1f}" '
            f'font-size="12" font-weight="600" text-anchor="{side}">{name}</text>'
        )
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


# ── entry points ─────────────────────────────────────────────────────────────────


def write_report(matrix: SweepMatrix, results_dir: Path = DEFAULT_RESULTS_DIR) -> Path:
    """Render REPORT.md (always) and comparison.svg (once plottable rows exist)."""
    docs, pending = load_row_results(matrix, results_dir)
    results_dir.mkdir(parents=True, exist_ok=True)
    report_path = results_dir / REPORT_NAME
    report_path.write_text(render_report_md(matrix, docs, pending), encoding="utf-8")
    svg = render_comparison_svg(docs)
    if svg is not None:
        (results_dir / CHART_NAME).write_text(svg, encoding="utf-8")
    return report_path


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        prog="benchmarks/report.py",
        description="Render the sweep results table + comparison chart (BUILD_PLAN §7).",
    )
    parser.add_argument("--matrix", type=Path, default=DEFAULT_MATRIX_PATH)
    parser.add_argument("--results", type=Path, default=DEFAULT_RESULTS_DIR)
    args = parser.parse_args(argv)
    matrix = load_matrix(args.matrix)
    path = write_report(matrix, args.results)
    print(path.read_text(encoding="utf-8"))
    print(f"written → {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
